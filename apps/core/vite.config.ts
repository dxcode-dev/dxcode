const alchemyLocal = process.env.DX_ALCHEMY_LOCAL === "1";
const checkoutLocal = process.env.DX_RUNTIME_MODE === "local";
const checkoutModelPreview = process.env.DX_LOCAL_MODEL_PREVIEW === "1";
const checkoutClaudeCode = process.env.DX_LOCAL_CLAUDE_CODE === "1";
const checkoutLocalVariableNames = [
  "DX_ENV",
  "DX_RUNTIME_MODE",
  "DX_AUTH_URL",
  "DX_AUTH_TRUSTED_ORIGINS",
  "DX_RUNNER_PROFILE_CATALOG",
  "DX_SOURCE_CONTROL_SCHEMA_VERSION",
  "DX_DXD_PUBLIC_URL",
  "DX_LOCAL_RUNTIME_URL",
  "DX_LOCAL_RUNTIME_TOKEN",
  "DX_INSTALLED_PLUGINS",
  "DX_ATTACHMENT_R2_ENDPOINT",
  "DX_ATTACHMENT_R2_CREDENTIALS",
] as const;
// Optional: preview other sign-in providers locally (see development-workflow.md),
// and Portals, which `pnpm dev` serves under `localhost:<core port>`.
const checkoutLocalOptionalVariableNames = [
  "DX_PORTAL_DOMAIN",
  "DX_SIGN_IN_PROVIDERS",
  "DX_SIGN_IN_ADMISSION",
  "DX_SIGN_IN_ALLOWED_EMAIL_DOMAINS",
  "DX_AUTH_EMAIL_FROM",
  // Web Push: generated by the local setup, absent in a checkout that
  // predates it, so push reports itself unavailable instead of failing.
  "DX_PUSH_VAPID_PUBLIC_KEY",
  "DX_PUSH_VAPID_PRIVATE_KEY",
  "DX_GOOGLE_CLIENT_ID",
  "DX_GOOGLE_CLIENT_SECRET",
  "DX_TERMS_URL",
  "DX_PRIVACY_URL",
] as const;

const localCallbackHost = (() => {
  const value = process.env.DX_DXD_PUBLIC_URL;
  if (value === undefined) return undefined;
  try {
    const url = new URL(value);
    if (
      url.protocol !== "https:" ||
      url.username !== "" ||
      url.password !== "" ||
      url.pathname !== "/" ||
      url.search !== "" ||
      url.hash !== ""
    )
      return undefined;
    return url.hostname;
  } catch {
    return undefined;
  }
})();

