// Bundles the account Orb Worker (src/execution/cloudflare/
// account-orb-worker.ts) into one ES module that Cloudflare connection
// preparation uploads into a person's or workspace's own account. The bundle
// is committed beside its entry, so Core, its tests, and the dev server all
// import it as text without a build step of their own.
//
//   node apps/core/scripts/build-account-orb-worker.mjs          # write
//   node apps/core/scripts/build-account-orb-worker.mjs --check  # drift
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { build } from "vite";

const core = resolve(import.meta.dirname, "..");
const entry = resolve(core, "src/execution/cloudflare/account-orb-worker.ts");
const output = resolve(
  core,
  "src/execution/cloudflare/account-orb-worker.generated.js",
);

const result = await build({
  configFile: false,
  logLevel: "warn",
  root: core,
  resolve: { conditions: ["workerd", "worker", "import", "module"] },
  build: {
    write: false,
    minify: false,
    target: "es2022",
    lib: { entry, formats: ["es"], fileName: () => "account-orb-worker.js" },
    rolldownOptions: { external: ["cloudflare:workers"] },
  },
});
const outputs = (Array.isArray(result) ? result : [result]).flatMap(
  ({ output: chunks }) => chunks,
);
const chunk = outputs.find(
  (item) => item.type === "chunk" && item.fileName === "account-orb-worker.js",
);
if (chunk === undefined || outputs.length !== 1)
  throw new Error(
    "The account Orb Worker must bundle into exactly one module.",
  );
const bundled = `// Generated by apps/core/scripts/build-account-orb-worker.mjs. Do not edit.\n${chunk.code}`;

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== bundled) {
    console.error(
      "account-orb-worker.generated.js is stale: run node apps/core/scripts/build-account-orb-worker.mjs",
    );
    process.exit(1);
  }
} else writeFileSync(output, bundled);
