// Writes apps/core/src/plugins/icons/lucide-icons.ts: each Lucide icon's
// shapes by kebab-case name, from the lucide-react the web app ships, so a
// plugin item's `lucide:<name>` is served as an SVG by URL
// (GET /v1/plugins/icons/lucide/:name) and the web app carries no icon data.
// Rerun after upgrading lucide-react:
//   node apps/core/scripts/generate-lucide-icons.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, "../../..");
const lucide = resolve(root, "apps/web/node_modules/lucide-react");
const icons = resolve(lucide, "dist/esm/icons");
const escapeXml = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;");
const shapes = {};
for (const file of readdirSync(icons).sort()) {
  if (!file.endsWith(".mjs")) continue;
  const { __iconNode: node } = await import(
    pathToFileURL(resolve(icons, file)).href
  );
  if (!Array.isArray(node)) continue;
  shapes[file.slice(0, -4)] = node
    .map(
      ([tag, attributes]) =>
        `<${tag} ${Object.entries(attributes)
          .filter(([name]) => name !== "key")
          .map(([name, value]) => `${name}="${escapeXml(value)}"`)
          .join(" ")}/>`,
    )
    .join("");
}
const { version } = JSON.parse(
  readFileSync(resolve(lucide, "package.json"), "utf8"),
);
writeFileSync(
  resolve(root, "apps/core/src/plugins/icons/lucide-icons.ts"),
  `// Generated by apps/core/scripts/generate-lucide-icons.mjs; do not edit.\n` +
    `export const LUCIDE_VERSION = ${JSON.stringify(version)};\n\n` +
    `/** Each Lucide icon's shapes, inside a 24 px stroked <svg>, by name. */\n` +
    `export const LUCIDE_SHAPES: Readonly<Record<string, string>> = JSON.parse(\n  ${JSON.stringify(JSON.stringify(shapes))},\n);\n`,
);
console.log(`lucide-react ${version}: ${Object.keys(shapes).length} icons`);
