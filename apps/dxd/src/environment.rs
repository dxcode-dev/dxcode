    #[test]
    fn thread_urls_follow_cores_grammar() {
        let id = "thr_0123abcd-4567-4abc-8def-0123456789ab";
        for valid in [
            format!("https://dx.example/threads/{id}"),
            format!("https://Dx-1.example:8443/threads/{id}"),
            format!("http://localhost:5173/threads/{id}"),
            format!("http://127.0.0.1/threads/{id}"),
            format!("http://[::1]:8787/threads/{id}"),
        ] {
            assert!(valid_thread_url(&valid), "{valid}");
        }
        for invalid in [
            format!("http://dx.example/threads/{id}"),
            format!("https://user@dx.example/threads/{id}"),
            format!("https://dx.example:/threads/{id}"),
            format!("https://dx.example:123456/threads/{id}"),
            format!("https:///threads/{id}"),
            format!("https://dx.example/x/threads/{id}"),
            format!("https://dx.example/threads/{id}?q"),
            format!("https://dx.example/threads/{id}#f"),
            format!("https://dx.example/threads/{}", id.to_uppercase()),
            format!("ftp://dx.example/threads/{id}"),
        ] {
            assert!(!valid_thread_url(&invalid), "{invalid}");
        }
    }
