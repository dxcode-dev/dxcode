fn ensure_local_profile(paths: &EnvironmentPaths) -> io::Result<()> {
    if !paths.local {
        return Ok(());
    }
    let expected = profile_hook(paths);
    match fs::read(&paths.profile) {
        Ok(existing) if existing == expected.as_bytes() => return Ok(()),
        Ok(_) => return Err(io::ErrorKind::PermissionDenied.into()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
        Err(error) => return Err(error),
    }
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(&paths.profile)?;
    file.write_all(expected.as_bytes())?;
    file.sync_all()
}

fn verify_profile(paths: &EnvironmentPaths) -> io::Result<()> {
    let expected = profile_hook(paths);
    let file = OpenOptions::new()
        .read(true)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(&paths.profile)?;
    let metadata = file.metadata()?;
    if !metadata.is_file()
        || metadata.uid() != paths.profile_owner
        || metadata.mode() & 0o022 != 0
        || metadata.len() != expected.len() as u64
    {
        return Err(io::ErrorKind::PermissionDenied.into());
    }
    let mut bytes = Vec::new();
    file.take(expected.len() as u64 + 1)
        .read_to_end(&mut bytes)?;
    if bytes == expected.as_bytes() {
        Ok(())
    } else {
        Err(invalid())
    }
}

fn ensure_history(directory: &File, paths: &EnvironmentPaths) -> io::Result<()> {
    let fd = openat(
        directory.as_raw_fd(),
        paths.history,
        libc::O_RDWR | libc::O_CREAT | libc::O_NOFOLLOW | libc::O_CLOEXEC,
        0o600,
    )?;
    // SAFETY: openat returned a newly owned descriptor.
    let file = unsafe { File::from_raw_fd(fd) };
    let mut metadata = file.metadata()?;
    // SAFETY: geteuid and getegid have no preconditions.
    let owner = unsafe { (libc::geteuid(), libc::getegid()) };
    if !metadata.is_file()
        || metadata.uid() != owner.0
        || metadata.gid() != owner.1
        || metadata.nlink() != 1
    {
        return Err(io::ErrorKind::PermissionDenied.into());
    }
    if metadata.mode() & 0o777 != 0o600 {
        file.set_permissions(fs::Permissions::from_mode(0o600))?;
        file.sync_all()?;
        metadata = file.metadata()?;
    }
    verify_private_file(&metadata, None)
}

