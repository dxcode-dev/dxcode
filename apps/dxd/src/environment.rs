pub(crate) fn valid_name(name: &str) -> bool {
    let mut bytes = name.bytes();
    let Some(first) = bytes.next() else {
        return false;
    };
    name.len() <= 64
        && (first == b'_' || first.is_ascii_uppercase())
        && bytes.all(|byte| byte == b'_' || byte.is_ascii_uppercase() || byte.is_ascii_digit())
        && !RESERVED_NAMES.contains(&name)
        && !name.starts_with("CF_")
        && !name.starts_with("CLOUDFLARE_")
        && !name.starts_with("DYLD_")
}

fn decode_entries(entries: &[EnvironmentEntry]) -> io::Result<BTreeMap<String, String>> {
    if entries.len() > MAX_ENVIRONMENT_ENTRIES {
        return Err(invalid());
    }
    let mut total = 0_usize;
    let mut previous: Option<&str> = None;
    let mut values = BTreeMap::new();
    for entry in entries {
        if !valid_name(&entry.name)
            || previous.is_some_and(|name| name >= entry.name.as_str())
            || entry.value_base64_url.is_empty()
            || entry.value_base64_url.contains('=')
        {
            return Err(invalid());
        }
        let decoded = URL_SAFE_NO_PAD
            .decode(&entry.value_base64_url)
            .map_err(|_| invalid())?;
        if URL_SAFE_NO_PAD.encode(&decoded) != entry.value_base64_url
            || decoded.is_empty()
            || decoded.len() > MAX_VALUE_BYTES
            || decoded.contains(&0)
        {
            return Err(invalid());
        }
        total = total.checked_add(decoded.len()).ok_or_else(invalid)?;
        if total > MAX_TOTAL_VALUE_BYTES {
            return Err(invalid());
        }
        let value = String::from_utf8(decoded).map_err(|_| invalid())?;
        previous = Some(&entry.name);
        values.insert(entry.name.clone(), value);
    }
    Ok(values)
}

struct Fragment {
    values: BTreeMap<String, String>,
}

fn generate_fragment(values: &BTreeMap<String, String>) -> io::Result<Vec<u8>> {
    let mut generated = ENVIRONMENT_HEADER.to_vec();
    for (name, value) in values {
        generated.extend_from_slice(name.as_bytes());
        generated.extend_from_slice(b"='");
        for byte in value.as_bytes() {
            if *byte == b'\'' {
                generated.extend_from_slice(b"'\\''");
            } else {
                generated.push(*byte);
            }
        }
        generated.extend_from_slice(b"'\n");
        if generated.len() > MAX_FRAGMENT_BYTES {
            return Err(invalid());
        }
    }
    Ok(generated)
}

fn parse_fragment(bytes: &[u8]) -> io::Result<Fragment> {
    if !bytes.starts_with(ENVIRONMENT_HEADER) || bytes.len() > MAX_FRAGMENT_BYTES {
        return Err(invalid());
    }
    let mut offset = ENVIRONMENT_HEADER.len();
    let mut values: BTreeMap<String, String> = BTreeMap::new();
    while offset < bytes.len() {
        let assignment = bytes[offset..]
            .windows(2)
            .position(|candidate| candidate == b"='")
            .ok_or_else(invalid)?
            + offset;
        let name = std::str::from_utf8(&bytes[offset..assignment]).map_err(|_| invalid())?;
        if !valid_name(name)
            || values
                .last_key_value()
                .is_some_and(|(previous, _)| previous.as_str() >= name)
        {
            return Err(invalid());
        }
        offset = assignment + 2;
        let mut value = Vec::new();
        loop {
            if bytes.get(offset..offset + 2) == Some(b"'\n") {
                offset += 2;
                break;
            }
            if bytes.get(offset..offset + 4) == Some(b"'\\''") {
                value.push(b'\'');
                offset += 4;
                continue;
            }
            let byte = *bytes.get(offset).ok_or_else(invalid)?;
            if byte == 0 || byte == b'\'' {
                return Err(invalid());
            }
            value.push(byte);
            offset += 1;
        }
        if value.is_empty() || value.len() > MAX_VALUE_BYTES {
            return Err(invalid());
        }
        let value = String::from_utf8(value).map_err(|_| invalid())?;
        values.insert(name.to_owned(), value);
    }
    if values.len() > MAX_ENVIRONMENT_ENTRIES {
        return Err(invalid());
    }
    Ok(Fragment { values })
}

fn parse_legacy_fragment(bytes: &[u8]) -> io::Result<Fragment> {
    if !bytes.starts_with(LEGACY_ENVIRONMENT_HEADER) || bytes.len() > MAX_FRAGMENT_BYTES {
        return Err(invalid());
    }
    let mut offset = LEGACY_ENVIRONMENT_HEADER.len();
    let mut removed: BTreeSet<String> = BTreeSet::new();
    let mut values: BTreeMap<String, String> = BTreeMap::new();
    let mut exports_started = false;
    while offset < bytes.len() {
        if bytes[offset..].starts_with(b"unset ") && !exports_started {
            offset += 6;
            let end = bytes[offset..]
                .iter()
                .position(|byte| *byte == b'\n')
                .ok_or_else(invalid)?
                + offset;
            let name = std::str::from_utf8(&bytes[offset..end]).map_err(|_| invalid())?;
            if !valid_name(name)
                || removed
                    .last()
                    .is_some_and(|previous| previous.as_str() >= name)
                || !removed.insert(name.to_owned())
            {
                return Err(invalid());
            }
            offset = end + 1;
            continue;
        }
        exports_started = true;
        if !bytes[offset..].starts_with(b"export ") {
            return Err(invalid());
        }
        offset += 7;
        let assignment = bytes[offset..]
            .windows(2)
            .position(|candidate| candidate == b"='")
            .ok_or_else(invalid)?
            + offset;
        let name = std::str::from_utf8(&bytes[offset..assignment]).map_err(|_| invalid())?;
        if !valid_name(name)
            || values
                .last_key_value()
                .is_some_and(|(previous, _)| previous.as_str() >= name)
        {
            return Err(invalid());
        }
        offset = assignment + 2;
        let mut value = Vec::new();
        loop {
            if bytes.get(offset..offset + 2) == Some(b"'\n") {
                offset += 2;
                break;
            }
            if bytes.get(offset..offset + 4) == Some(b"'\\''") {
                value.push(b'\'');
                offset += 4;
                continue;
            }
            let byte = *bytes.get(offset).ok_or_else(invalid)?;
            if byte == 0 || byte == b'\'' {
                return Err(invalid());
            }
            value.push(byte);
            offset += 1;
        }
        if value.is_empty() || value.len() > MAX_VALUE_BYTES {
            return Err(invalid());
        }
        values.insert(
            name.to_owned(),
            String::from_utf8(value).map_err(|_| invalid())?,
        );
    }
    if removed.len() > MAX_ENVIRONMENT_ENTRIES
        || values.len() > MAX_ENVIRONMENT_ENTRIES
        || removed.iter().any(|name| values.contains_key(name))
    {
        return Err(invalid());
    }
    Ok(Fragment { values })
}

