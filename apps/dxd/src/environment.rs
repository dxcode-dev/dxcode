    #[test]
    fn complete_write_handles_short_writes_and_rejects_write_zero() {
        struct ShortWriter {
            bytes: Vec<u8>,
            maximum: usize,
            stop_after: Option<usize>,
        }
        impl Write for ShortWriter {
            fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
                if self
                    .stop_after
                    .is_some_and(|bound| self.bytes.len() >= bound)
                {
                    return Ok(0);
                }
                let length = bytes.len().min(self.maximum);
                self.bytes.extend_from_slice(&bytes[..length]);
                Ok(length)
            }

            fn flush(&mut self) -> io::Result<()> {
                Ok(())
            }
        }
        let expected = b"complete materialization";
        let mut short = ShortWriter {
            bytes: Vec::new(),
            maximum: 2,
            stop_after: None,
        };
        write_complete(&mut short, expected).unwrap();
        assert_eq!(short.bytes, expected);

        let mut stopped = ShortWriter {
            bytes: Vec::new(),
            maximum: 3,
            stop_after: Some(3),
        };
        assert_eq!(
            write_complete(&mut stopped, expected).unwrap_err().kind(),
            io::ErrorKind::WriteZero
        );
        assert_ne!(stopped.bytes, expected);
    }

