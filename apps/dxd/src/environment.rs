fn git_config_value(value: &str) -> String {
    let escaped = value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\t', "\\t")
        .replace('\u{8}', "\\b");
    format!("\"{escaped}\"")
}

