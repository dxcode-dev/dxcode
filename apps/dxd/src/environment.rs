#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct GitBitbucketGateway {
    pub origin: String,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum EnvironmentOutcome {
    Applied,
    Unchanged,
    Superseded,
    Unavailable,
    /// `environment.check` did not match the applied activation; send it.
    Missing,
    /// The `.agents/resume` hook exceeded its time bound.
    ResumeTimeout,
}

#[derive(Clone, Copy, Debug, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum EnvironmentShell {
    NoShell,
    Current,
    RestartRequired,
}

#[derive(Serialize)]
pub struct EnvironmentResult {
    pub kind: EnvironmentOutcome,
    pub generation: u64,
    pub shell: EnvironmentShell,
}

