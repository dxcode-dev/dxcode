// --- WebRTC guard -------------------------------------------------------
// Chromium ignores CSP's `webrtc` directive, so a sealed frame could open
// peer connections and send data out over STUN or TURN, past
// `default-src 'none'`. A realm only gets `RTCPeerConnection` back from a
// fresh realm, and a sandboxed view's only fresh realms are nested frames
// (popups are off, workers have no peer connections). So an untrusted view
// loses every `RTC*` global in its own realm and may not hold a nested
// frame:
//
// 1. The shell sanitizes the view's whole document before writing it.
// 2. Every HTML string sink goes through dx's Trusted Types default policy,
//    which sanitizes it the same way; the CSP allows no other native policy,
//    and `trustedTypes.createPolicy` returns a policy that goes through dx's.
// 3. The same sinks are wrapped where Trusted Types is missing, and sweep
//    nested frames synchronously after they run.
// 4. `createElement`, `createElementNS`, and `customElements.define` refuse
//    frame elements; a MutationObserver removes any that still appears.
//
// Sanitizing parses the markup into an inert `<template>` (scripting on,
// as the view's own parse is), removes every frame element in any
// namespace, nested templates included, and serializes it; it repeats until
// the markup is stable, so markup that would only turn into a frame after
// a round trip is caught. Only a trusted-tier pane that declares
// `connect.webrtc` runs without the guard.

/**
 * Detects (never removes) a frame start or end tag exactly as the HTML
 * tokenizer reads one: `<`, the name in any case, then whitespace, `/`,
 * `>`, or the end. Markup without one cannot make a frame element, so it
 * skips sanitizing untouched.
 */
const FRAME_TAG =
  /<\/?(?:iframe|frame|frameset|object|embed|fencedframe|portal)(?:[\t\n\f\r />]|$)/i;

/**
 * The sanitizer, as source both the shell and the guard define. `parse`
 * puts markup into a template and `serialize` reads it back; both are the
 * caller's own, so the guard can use the native setters it saved.
 */
const sanitizerSource = `
  const FRAME_NAMES = new Set(["iframe", "frame", "frameset", "object", "embed", "fencedframe", "portal"]);
  const FRAME_TAG = ${FRAME_TAG.toString()};
  // noscript too: views always run script, so it never shows, and a
  // parser without scripting reads its content differently (mXSS).
  const strip = (root) => {
    let removed = 0;
    for (const element of Array.from(root.querySelectorAll("*"))) {
      const name = String(element.localName).toLowerCase();
      if (FRAME_NAMES.has(name) || name === "noscript") { element.remove(); removed++; }
      else if (name === "template" && element.content) removed += strip(element.content);
    }
    return removed;
  };
  const sanitizeWith = (parse, serialize) => (markup) => {
    let html = String(markup);
    for (let round = 0; round < 4; round++) {
      if (!FRAME_TAG.test(html)) return html;
      const root = parse(html);
      const removed = strip(root);
      const next = serialize(root);
      if (removed === 0 && next === html) return html;
      html = next;
    }
    return "";
  };`;

const webrtcGuard = `(() => {
  // Fails closed: if any step throws, the rest of the view is never parsed
  // (it becomes inert text) and the transcript shows the error.
  const stopView = Document.prototype.write;
  try {
  const apply = Reflect.apply;
  const define = Object.defineProperty;
  const describe = Object.getOwnPropertyDescriptor;
  ${sanitizerSource}
  const createElement = Document.prototype.createElement;
  const innerHTML = describe(Element.prototype, "innerHTML");
  const templateInnerHTML = describe(HTMLTemplateElement.prototype, "innerHTML") ?? innerHTML;
  let inside = false;
  const owners = new WeakMap();
  const sanitize = sanitizeWith(
    (html) => {
      const template = apply(createElement, document, ["template"]);
      apply(templateInnerHTML.set, template, [html]);
      owners.set(template.content, template);
      return template.content;
    },
    (content) => apply(templateInnerHTML.get, owners.get(content), []),
  );
  const clean = (html) => {
    if (inside) return String(html);
    inside = true;
    try { return sanitize(html); } finally { inside = false; }
  };
  const FRAME = /^(?:iframe|frame|frameset|object|embed|fencedframe|portal)$/i;
  const localName = describe(Element.prototype, "localName").get;
  const isFrame = (node) => { try { return FRAME.test(apply(localName, node, [])); } catch { return false; } };
  const refuse = () => { throw new DOMException("dx views cannot hold frames or WebRTC.", "NotSupportedError"); };
  // 1. No WebRTC in this realm, nor XSLT, which builds markup past the policy.
  const stripRealm = (global) => {
    for (const name of Object.getOwnPropertyNames(global))
      if (/^(?:webkit|moz)?RTC/.test(name) || name === "XSLTProcessor") {
        try { delete global[name]; } catch {}
        try { define(global, name, { value: undefined, writable: false, configurable: false }); } catch {}
      }
  };
  stripRealm(globalThis);
  // 2. Trusted Types: dx's default policy sanitizes every HTML sink. Other
  // policies are dx's shims, so libraries keep working through it.
  const factory = globalThis.trustedTypes;
  if (factory) {
    const policy = factory.createPolicy("default", { createHTML: clean, createScript: (s) => s, createScriptURL: (s) => s });
    const names = new Set(["default"]);
    define(Object.getPrototypeOf(factory), "createPolicy", { value(name, rules) {
      name = String(name);
      if (names.has(name)) throw new TypeError("Policy with name \\"" + name + "\\" already exists.");
      names.add(name);
      const own = (key) => (typeof rules?.[key] === "function" ? rules[key] : null);
      const html = own("createHTML"), script = own("createScript"), url = own("createScriptURL");
      const fail = (key) => () => { throw new TypeError("Policy " + name + "'s " + key + " is missing."); };
      return Object.freeze({
        name,
        createHTML: html ? (input, ...args) => policy.createHTML(String(apply(html, rules, [input, ...args]))) : fail("createHTML"),
        createScript: script ? (input, ...args) => policy.createScript(String(apply(script, rules, [input, ...args]))) : fail("createScript"),
        createScriptURL: url ? (input, ...args) => policy.createScriptURL(String(apply(url, rules, [input, ...args]))) : fail("createScriptURL"),
      });
    }, writable: false, configurable: false });
  }
  // 3. No frame element may ever be connected. Every native this uses is
  // kept here, before any of the view's scripts can replace it. A frame is
  // an element in the XHTML namespace with a frame's local name, however it
  // was made: the HTML parser, the XML parser (any prefix, any MIME type),
  // or the DOM. Strings are cleaned before they are parsed (above); what a
  // parser or the DOM builds is purged after; what is inserted is purged
  // before; and a sweep after each, and on every mutation in the document
  // and in every shadow root, removes anything left.
  const XHTML = "http://www.w3.org/1999/xhtml";
  const nsOf = describe(Element.prototype, "namespaceURI").get;
  const typeOf = describe(Node.prototype, "nodeType").get;
  const parentOf = describe(Node.prototype, "parentNode").get;
  const hostOf = describe(ShadowRoot.prototype, "host").get;
  const contentOf = describe(HTMLTemplateElement.prototype, "content").get;
  const shadowOf = describe(Element.prototype, "shadowRoot").get;
  const documentElementOf = describe(Document.prototype, "documentElement").get;
  const removeNode = Element.prototype.remove;
  const contains = Node.prototype.contains;
  const queryAll = { 1: Element.prototype.querySelectorAll, 9: Document.prototype.querySelectorAll, 11: DocumentFragment.prototype.querySelectorAll };
  const observe = MutationObserver.prototype.observe;
  const nodeType = (node) => { try { return apply(typeOf, node, []); } catch { return 0; } };
  const isFrameElement = (node) => {
    try { return nodeType(node) === 1 && apply(nsOf, node, []) === XHTML && FRAME_NAMES.has(apply(localName, node, [])); }
    catch { return false; }
  };
  const SELECTOR = "iframe,frame,frameset,object,embed,fencedframe,portal,template";
  // Every shadow root this realm made (attachShadow, ElementInternals).
  const roots = new Set();
  /** Removes every frame under node: in it, its templates, its shadow roots. */
  const purge = (node, depth = 0, deep = false) => {
    const query = queryAll[nodeType(node)];
    if (query === undefined || depth > 32) return;
    if (isFrameElement(node)) { apply(removeNode, node, []); return; }
    if (nodeType(node) === 1 && apply(localName, node, []) === "template") { try { purge(apply(contentOf, node, []), depth + 1); } catch {} }
    for (const element of Array.from(apply(query, node, [SELECTOR]))) {
      if (isFrameElement(element)) apply(removeNode, element, []);
      else if (apply(localName, element, []) === "template") { try { purge(apply(contentOf, element, []), depth + 1); } catch {} }
    }
    // Shadow roots whose host is under node, and theirs in turn.
    for (const root of roots) {
      let host;
      try { host = apply(hostOf, root, []); } catch { continue; }
      if (host !== node && apply(contains, node, [host])) purge(root, depth + 1);
    }
    if (nodeType(node) === 1) { const open = apply(shadowOf, node, []); if (open) purge(open, depth + 1, deep); }
    // Parsers make declarative shadow roots this realm never attached:
    // what they built is walked into every open one too.
    if (deep)
      for (const element of Array.from(apply(query, node, ["*"]))) {
        const open = apply(shadowOf, element, []);
        if (open) { watch(open); purge(open, depth + 1, true); }
      }
  };
  /** Purges a parsed document; a frame as its root element is removed. */
  const purgeDocument = (doc) => {
    try { const root = apply(documentElementOf, doc, []); if (isFrameElement(root)) apply(removeNode, root, []); } catch {}
    purge(doc, 0, true);
    return doc;
  };
  const sweep = () => {
    if (globalThis.length > 0)
      for (let index = 0; index < globalThis.length; index++) {
        try { stripRealm(globalThis[index]); } catch {}
      }
    purge(document);
    for (const root of roots) purge(root);
  };
  const observer = new MutationObserver(sweep);
  const watch = (root) => {
    if (root == null || roots.has(root)) return;
    roots.add(root);
    apply(observe, observer, [root, { childList: true, subtree: true }]);
  };
  const text = (value) => (typeof value === "string" ? clean(value) : value);
  /** A string sink: its markup cleaned before, what it built purged after. */
  const wrapSetter = (proto, key, targets) => {
    const d = proto && describe(proto, key);
    if (!d?.set) return;
    const set = d.set;
    define(proto, key, { ...d, set(value) {
      const purgeAfter = targets(this);
      try { return apply(set, this, [text(value)]); } finally { for (const target of purgeAfter) purge(target, 0, true); sweep(); }
    }, configurable: false });
  };
  const wrapMethod = (target, key, index, after) => {
    const original = target?.[key];
    if (typeof original !== "function") return;
    define(target, key, { value(...args) {
      if (index === "all") args = args.map(text);
      else if (index !== null) args[index] = text(args[index]);
      const purgeAfter = after?.before?.(this) ?? [];
      let result;
      try { result = apply(original, this, args); return after?.result ? after.result(result, args) : result; }
      finally { for (const node of purgeAfter) purge(node, 0, true); sweep(); }
    }, writable: false, configurable: false });
  };
  const self = (node) => [node];
  const selfAndParent = (node) => { let up = null; try { up = apply(parentOf, node, []); } catch {} return up ? [node, up] : [node]; };
  for (const proto of [Element.prototype, ShadowRoot.prototype]) {
    wrapSetter(proto, "innerHTML", self);
    for (const key of ["setHTMLUnsafe", "setHTML"])
      wrapMethod(proto, key, 0, { before: (node) => (nodeType(node) === 1 ? [node, apply(shadowOf, node, [])].filter(Boolean) : [node]) });
  }
  wrapSetter(Element.prototype, "outerHTML", (node) => selfAndParent(node).slice(1));
  wrapMethod(Element.prototype, "insertAdjacentHTML", 1, { before: selfAndParent });
  // write and writeln feed one stream across calls: a tag split over two
  // calls is held back until it is whole, so each call sees whole tags.
  const nativeWrite = Document.prototype.write;
  let pending = "";
  // Only a tail that could still become a frame tag is held back.
  const heldTail = (html) => {
    const at = html.lastIndexOf("<");
    if (at === -1) return -1;
    const name = html.slice(at + 1).replace(/^\\//, "").toLowerCase();
    return /^[a-z]*$/.test(name) && [...FRAME_NAMES].some((frame) => frame.startsWith(name)) ? at : -1;
  };
  for (const key of ["write", "writeln"]) {
    const original = Document.prototype[key];
    define(Document.prototype, key, { value(...args) {
      let html = pending + args.map(String).join("") + (key === "writeln" ? "\\n" : "");
      const at = heldTail(html);
      pending = at === -1 ? "" : html.slice(at);
      if (at !== -1) html = html.slice(0, at);
      try { return apply(original, this, [clean(html)]); } finally { sweep(); }
    }, writable: false, configurable: false });
  }
  const write = nativeWrite, close = Document.prototype.close;
  define(Document.prototype, "close", { value() {
    if (pending !== "") { const html = pending; pending = ""; apply(write, this, [clean(html)]); sweep(); }
    return apply(close, this, []);
  }, writable: false, configurable: false });
  wrapMethod(Document.prototype, "execCommand", 2);
  // Parsers: any MIME type, so the XML parser too; their result is purged.
  const purgedResult = { result: (result) => { if (nodeType(result) === 9) purgeDocument(result); else purge(result, 0, true); return result; } };
  wrapMethod(globalThis.DOMParser?.prototype, "parseFromString", 0, purgedResult);
  wrapMethod(globalThis.Range?.prototype, "createContextualFragment", 0, purgedResult);
  wrapMethod(Document, "parseHTMLUnsafe", 0, purgedResult);
  wrapMethod(Document, "parseHTML", 0, purgedResult);
  for (const key of ["createDocument", "createHTMLDocument"]) wrapMethod(globalThis.DOMImplementation?.prototype, key, null, purgedResult);
  for (const key of ["importNode", "adoptNode"]) wrapMethod(Document.prototype, key, null, purgedResult);
  wrapMethod(Node.prototype, "cloneNode", null, purgedResult);
  // Insertion, on every interface that has it: a frame is refused, and
  // frames under what is inserted are removed before it is connected.
  const guardInsert = (args) => {
    for (const node of args) {
      if (isFrameElement(node)) refuse();
      purge(node);
    }
  };
  const wrapInsert = (proto, key) => {
    const original = proto && Object.hasOwn(proto, key) ? proto[key] : undefined;
    if (typeof original !== "function") return;
    define(proto, key, { value(...args) {
      guardInsert(args);
      try { return apply(original, this, args); } finally { sweep(); }
    }, writable: false, configurable: false });
  };
  for (const proto of [Node.prototype, Element.prototype, Document.prototype, DocumentFragment.prototype, CharacterData.prototype, DocumentType.prototype, globalThis.Range?.prototype])
    for (const key of ["appendChild", "insertBefore", "replaceChild", "append", "prepend", "after", "before", "replaceWith", "replaceChildren", "insertAdjacentElement", "moveBefore", "insertNode", "surroundContents"])
      wrapInsert(proto, key);
  // Shadow roots, open or closed: watched and swept like the document.
  const attachShadow = Element.prototype.attachShadow;
  define(Element.prototype, "attachShadow", { value(...args) {
    const root = apply(attachShadow, this, args);
    watch(root);
    return root;
  }, writable: false, configurable: false });
  const internalsRoot = globalThis.ElementInternals && describe(ElementInternals.prototype, "shadowRoot");
  if (internalsRoot?.get) {
    const get = internalsRoot.get;
    define(ElementInternals.prototype, "shadowRoot", { ...internalsRoot, get() { const root = apply(get, this, []); if (root) { watch(root); purge(root); } return root; }, configurable: false });
  }
  // 4. No frame elements from the DOM either.
  for (const key of ["createElement", "createElementNS"]) {
    const original = Document.prototype[key];
    define(Document.prototype, key, { value(...args) {
      const node = apply(original, this, args);
      if (isFrame(node)) refuse();
      return node;
    }, writable: false, configurable: false });
  }
  const registry = globalThis.CustomElementRegistry?.prototype;
  if (registry?.define) {
    const original = registry.define;
    define(registry, "define", { value(name, constructor, options) {
      const extended = options == null ? undefined : options.extends;
      if (extended !== undefined && FRAME.test(String(extended))) refuse();
      return apply(original, this, [name, constructor, extended === undefined ? undefined : { extends: String(extended) }]);
    }, writable: false, configurable: false });
  }
  for (const proto of [globalThis.HTMLIFrameElement?.prototype, globalThis.HTMLObjectElement?.prototype, globalThis.HTMLFrameElement?.prototype])
    for (const key of ["contentWindow", "contentDocument"]) {
      const d = proto && describe(proto, key);
      if (!d?.get) continue;
      const get = d.get;
      define(proto, key, { ...d, get() { sweep(); return null; }, configurable: false });
    }
  apply(observe, observer, [document, { childList: true, subtree: true }]);
  } catch (error) {
    parent.postMessage({ source: "${VIEW_FRAME_MESSAGE}", type: "error", message: "dx could not guard this view, so it did not run: " + String(error) }, "*");
    Reflect.apply(stopView, document, ["<plaintext hidden>"]);
  }
})();`;

