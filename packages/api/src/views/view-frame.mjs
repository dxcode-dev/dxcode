/**
 * The app's contrast and forced-colors overrides as MCP Apps variables.
 * `!important`, so they also beat the `styles.variables` the kit and other
 * MCP Apps set inline on the root. A frame evaluates the same media queries
 * as the app, so it follows the person's setting as the app does.
 */
const pluginContrastCss = (() => {
  // Every role as a reference to the MCP Apps variable that carries it.
  const roleVariables = pluginColors(
    Object.fromEntries(
      Object.keys(PLUGIN_ROLES).map((role) => [role, `@${role}`]),
    ),
  );
  const references = Object.fromEntries(
    Object.entries(PLUGIN_ROLES).map(([role, source]) => [
      source,
      Object.keys(roleVariables).find(
        (name) => roleVariables[name] === `@${role}`,
      ),
    ]),
  );
  const asReferences = Object.fromEntries(
    Object.entries(PLUGIN_ROLES).map(([role, source]) => [
      role,
      `var(${references[source]})`,
    ]),
  );
  const base = pluginColors(asReferences);
  return Object.entries(CONTRAST_MEDIA)
    .map(([key, media]) => {
      const overrides = DESIGN_SYSTEM.contrast[key] ?? {};
      const roles = Object.fromEntries(
        Object.entries(PLUGIN_ROLES).map(([role, source]) => [
          role,
          (overrides[source] === undefined
            ? undefined
            : renameVariables(overrides[source], references)) ??
            asReferences[role],
        ]),
      );
      const changed = Object.entries(pluginColors(roles)).filter(
        ([name, value]) => value !== base[name],
      );
      return changed.length === 0
        ? ""
        : `@media ${media}{:root{${changed.map(([name, value]) => `${name}:${value}!important`).join(";")}}}`;
    })
    .join("");
})();

/** Where a plugin frame asks for the kit; the host inlines it there. */
export const PLUGIN_UI_SPECIFIER = "dx:plugin-ui";
// Quoted or not, closed or not: any script tag whose src is the kit.
const pluginUiTag =
  /<script\b[^>]*?\bsrc\s*=\s*(["']?)dx:plugin-ui\1(?=[\s>/])[^>]*>(?:\s*<\/script\s*>)?/gi;

/** Whether `source` asks for `@dxcode/plugin-ui`. */
export const usesPluginUi = (source) =>
  source.includes(PLUGIN_UI_SPECIFIER) &&
  new RegExp(pluginUiTag.source, "i").test(source);

/**
 * `source` with its first kit tag replaced by the kit's code and any later
 * ones dropped. Without the kit's code, the tags are dropped and the page
 * stays plain HTML.
 */
const inlinePluginUi = (source, pluginUi) => {
  let first = true;
  return source.replace(pluginUiTag, () => {
    if (!first || pluginUi === undefined) return "";
    first = false;
    // The code is inside a <script>: no `</script` may end it early.
    return `<script type="module">${pluginUi.replace(/<\/(script)/gi, "<\\/$1")}</script>`;
  });
};
