/**
 * `value` with each `var(--x)` renamed through `names`, or undefined when
 * it reads a variable `names` lacks.
 */
const renameVariables = (value, names) => {
  let known = true;
  const renamed = value.replace(/var\((--[\w-]+)\)/g, (_, name) => {
    const target = names[name];
    if (target === undefined) known = false;
    return `var(${target})`;
  });
  return known ? renamed : undefined;
};

